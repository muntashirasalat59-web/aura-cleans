#!/usr/bin/env node
/**
 * Builds backend/database/supabase.full-setup.sql — one file that sets up a NEW, empty
 * Supabase project for the app. It joins the repo's SQL files in dependency order.
 *
 *   node backend/scripts/build-setup-sql.js
 *
 * Files marked SUPERSEDED in their header are left out on purpose.
 */
const fs = require('fs');
const path = require('path');

const DB_DIR = path.join(__dirname, '..', 'database');

const PARTS = [
  'setup/00_prelude.sql',
  'supabase.schema.sql',
  'supabase.migration.user_profiles.sql',
  'supabase.migration.phone_trial_support.sql',
  'supabase.migration.support_messages_admin_read.sql',
  'supabase.migration.business_settings.sql',
  'supabase.migration.monthly_sales_target.sql',
  'supabase.migration.activity_log.sql',
  'supabase.migration.user_dashboard_preferences.sql',
  'supabase.migration.products_complete.sql',
  'supabase.migration.products_details.sql',
  'supabase.migration.products_fragrance.sql',
  'supabase.migration.products_hsn.sql',
  'supabase.migration.products_retail_price.sql',
  'supabase.migration.soft_delete.sql',
  'supabase.migration.parties_manufacturer.sql',
  'supabase.migration.purchases_sales_complete.sql',
  'supabase.migration.purchases_sales_step1_columns.sql',
  'supabase.migration.expenses.sql',
  'supabase.migration.employees.sql',
  'supabase.migration.sales_payment.sql',
  'supabase.migration.sales_amount_paid.sql',
  'supabase.migration.sales_payment_status.sql',
  'supabase.migration.sales_partial_received.sql',
  'supabase.migration.sales_place_of_supply.sql',
  'supabase.migration.sales_ship_to.sql',
  'supabase.migration.sales_is_gst_invoice.sql',
  'supabase.migration.sales_discount.sql',
  'supabase.migration.purchases_gst.sql',
  'supabase.migration.purchases_payment.sql',
  'supabase.migration.business_cities.sql',
  'supabase.migration.expenses_more_categories.sql',
  // Functions (later files replace earlier versions of the same function)
  'supabase.functions.sql',
  'supabase.migration.purchases_sales_step2_function.sql',
  'supabase.migration.purchase_party_balance.sql',
  'supabase.migration.apply_sale_payment_fn.sql',
  'supabase.migration.sale_atomic_payment.sql',
  'supabase.migration.update_sale.sql',
  'supabase.migration.stock_restore_on_delete.sql',
  'supabase.migration.sales_soft_delete.sql',
  'supabase.migration.delete_party_cascade.sql',
  'supabase.migration.delete_product_smart.sql',
  'supabase.migration.next_invoice_number.sql',
  // Pre-bookings + offers
  'supabase.rebuild.pre_bookings.sql',
  'supabase.migration.pre_bookings_invoice.sql',
  'supabase.migration.pre_bookings_update.sql',
  'supabase.migration.offers.sql',
  'supabase.migration.offer_items_rate.sql',
  'supabase.migration.delete_business_cascade.sql',
  'supabase.migration.invoices_storage.sql',
  'supabase.migration.realtime.sql',
  // Must be last: business_id on every table + per-business row security.
  'setup/99_multi_business.sql',
];

const header = `-- =====================================================================
-- AURA CLEANS — full database setup for a NEW, EMPTY Supabase project
-- GENERATED by backend/scripts/build-setup-sql.js — edit the source files, not this one.
--
-- How to use: Supabase -> SQL Editor -> New query -> paste this whole file -> Run.
-- The editor runs it as one transaction: if anything fails, nothing is applied.
-- Then create your login (see the end of this file).
-- =====================================================================
`;

const out = [header];
for (const rel of PARTS) {
  const full = path.join(DB_DIR, rel);
  const sql = fs.readFileSync(full, 'utf8').replace(/\r\n/g, '\n');
  // NOTIFY inside a transaction is harmless, but keep one at the very end instead.
  out.push(`\n\n-- ######## ${rel} ########\n${sql.replace(/^\s*NOTIFY pgrst.*$/gim, '')}`);
}
out.push("\n\nNOTIFY pgrst, 'reload schema';\n");

const target = path.join(DB_DIR, 'supabase.full-setup.sql');
fs.writeFileSync(target, out.join(''));
console.log(`Wrote ${path.relative(process.cwd(), target)} (${PARTS.length} parts)`);
